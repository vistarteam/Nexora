"""Shared helpers for engine tests."""

from __future__ import annotations

import math
from typing import Any


def make_candles(
    count: int,
    start: float = 100.0,
    drift: float = 0.0,
    amplitude: float = 0.0,
    period: float = 20.0,
    start_time: int = 1_700_000_000_000,
    step_ms: int = 3_600_000,
) -> list[dict[str, Any]]:
    """Build a deterministic synthetic candle series.

    This is *test input*, generated by the test - not by the application. The
    engine under test has no idea these numbers are synthetic, which is exactly
    what makes it a fair test of the engine's maths and status handling.
    """
    candles: list[dict[str, Any]] = []
    price = start
    for index in range(count):
        wave = amplitude * math.sin((2 * math.pi * index) / period)
        open_price = price
        close_price = max(0.01, price * (1 + drift) + wave * 0.1)
        high = max(open_price, close_price) * 1.002
        low = min(open_price, close_price) * 0.998
        candles.append(
            {
                "time": start_time + index * step_ms,
                "open": round(open_price, 6),
                "high": round(high, 6),
                "low": round(low, 6),
                "close": round(close_price, 6),
                "volume": 1000 + (index % 50) * 10,
            }
        )
        price = close_price
    return candles
